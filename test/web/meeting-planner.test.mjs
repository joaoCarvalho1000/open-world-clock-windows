import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {startOnFreePort} from './serve.mjs';
const require=createRequire(new URL('../../cloudflare/package.json',import.meta.url));
const puppeteer=require('puppeteer-core');
const server=await startOnFreePort(8851,8860);
const browser=await puppeteer.launch({executablePath:process.env.CHROME_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe','/usr/bin/google-chrome','/usr/bin/chromium'].find(fs.existsSync),headless:true});
fs.mkdirSync('output/overlap-audit/web',{recursive:true});
try {
for(const width of [390,1440]) {
 const context=await browser.createBrowserContext(); const page=await context.newPage();await page.setViewport({width,height:1000});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(server.url+'/meeting-planner#c=Europe/London,America/New_York,Pacific/Auckland&z=America/New_York',{waitUntil:'networkidle0'});
 await page.waitForSelector('.tool-window.is-ready'); const app=await(await page.$('#heroApp')).contentFrame();
 await app.waitForSelector('#planFind:not([hidden])');
 await app.select('#convZone','Pacific/Auckland'); await app.click('#planFind');
 await app.waitForSelector('.find-item.recommended');
 assert.equal(await app.$$eval('.find-item',els=>els.length),3);
 assert.equal(await app.$eval('.find-controls select',el=>el.value),'balanced');
 assert.ok(await app.$eval('.find-local',el=>/\d/.test(el.textContent)));
 assert.equal(await app.$eval('[data-preference=mode]',el=>el.value),'next');
 assert.ok(await app.$$eval('.find-item',els=>els.every(el=>+el.dataset.start>=Date.now() && +el.dataset.start<Date.now()+48*3600000)));
 await app.select('.find-controls label:nth-child(2) select','family');
 await app.select('.find-controls label:nth-child(3) select','90');
 await page.screenshot({path:`output/overlap-audit/web/planner-${width}.png`});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await app.click('.find-people summary');
 const before=await app.$$eval('.recommended .find-local',els=>els.length);
 await app.evaluate(()=>[...document.querySelectorAll('.find-person')].find(el=>el.textContent.includes('Auckland')).querySelector('input[type=checkbox]').click());
 assert.equal(await app.$$eval('.recommended .find-local',els=>els.length),before-1);
 await app.$eval('.find-person input[type=time]',el=>{el.value='';el.dispatchEvent(new Event('input',{bubbles:true}));});
 assert.equal(await app.$$eval('.find-item',els=>els.length),0);
 await app.$eval('.find-person input[type=time]',el=>el.dispatchEvent(new Event('change',{bubbles:true})));
 assert.equal(await app.$$eval('.find-item',els=>els.length),3);
 await app.evaluate(()=>{window.captured={};window.wc={...window.wc,copyText:async text=>{window.captured.copy=text;return true;},saveIcs:async payload=>{window.captured.invite=payload;return true;}};});
 await app.click('.find-item.recommended');assert.equal(await app.$eval('#planFindPanel',el=>el.hidden),true);
 const selected=await app.evaluate(()=>window.WCConverter.state().meeting);
 assert.equal(selected.participants.includes('Pacific/Auckland'),false);
 assert.equal(selected.sourceZone==='Pacific/Auckland',false);
 const shared=await app.evaluate(()=>window.WCLink.parse(window.WCShareHash()));
 assert.deepEqual(shared.zones,selected.participants);
 await app.click('#planCopy');assert.equal(await app.evaluate(()=>window.captured.copy.includes('Auckland')),false);
 await app.click('#planIcs');assert.equal(await app.evaluate(()=>window.captured.invite.description.includes('Auckland')),false);
 await app.evaluate(()=>{window.savedShareHash=window.WCShareHash;window.WCShareHash=undefined;});
 await app.click('#planLink');
 assert.equal(await app.evaluate(()=>window.WCLink.parse(new URL(window.captured.copy).hash).zones.includes('Pacific/Auckland')),false);
 await app.evaluate(()=>{window.WCShareHash=window.savedShareHash;const p=window.WCLink.parse(window.WCShareHash());window.WCConverter.apply(p.z,p.startMs,p.endMs,p.zones);});
 assert.deepEqual(await app.evaluate(()=>window.WCConverter.state().meeting.participants),selected.participants);
 await app.click('#planFind');
 assert.equal(await app.$eval('.find-controls label:nth-child(2) select',el=>el.value),'family');
 assert.equal(await app.$eval('.find-controls label:nth-child(3) select',el=>el.value),'90');
 assert.equal(await app.evaluate(()=>JSON.parse(localStorage.getItem('owc-meeting-preferences')).preset),'family');
 await app.click('#planFind');
 await app.evaluate(()=>{const state=window.WCConverter.state().meeting;const start=Date.now()-3*86400000;window.WCConverter.apply(state.sourceZone,start,start+3600000,state.participants);});
 await app.click('#planFind');await app.select('[data-preference=mode]','explore');
 assert.ok(await app.$$eval('.find-item strong',els=>els.some(el=>el.textContent.includes('past'))));
 await app.select('[data-preference=mode]','next');
 assert.ok(await app.$$eval('.find-item',els=>els.every(el=>+el.dataset.start>=Date.now())));
 assert.deepEqual(errors,[]);await context.close();
}
console.log('Balanced planner controls, participant filtering, exact selection and responsive layout passed.');
}finally{await browser.close();await server.close();}
